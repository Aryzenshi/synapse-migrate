"""Reverse DDL compiler. Pre-load tables/uniques are separate from post-load constraints."""
from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from jinja2 import Environment, FileSystemLoader

from synapse.domain.heuristics.thresholds import Thresholds
from synapse.domain.ir.document import Collection, DocumentIR, FieldDecision, FieldKind, FieldNode, ReverseAction
from synapse.domain.naming import NameRegistry, child_table_name, flatten_path, quote_identifier, quote_qualified
from synapse.domain.typemap.bson_to_sql import SqlTypeSpec, bson_to_sql

_TEMPLATE_DIR = Path(__file__).with_name("templates")
_ENV = Environment(loader=FileSystemLoader(_TEMPLATE_DIR), autoescape=False, trim_blocks=True, lstrip_blocks=True)


@dataclass
class RelationalArtifacts:
    pre_load_sql: str
    post_load_sql: str
    verification_sql: str
    tables: list[dict[str, Any]]
    naming: dict[str, str]
    not_translated: list[dict[str, str]]
    warnings: list[dict[str, str]]


class RelationalEmitter:
    def __init__(self, *, dialect: str = "mysql", options: dict[str, Any] | None = None):
        dialect = dialect.lower()
        if dialect not in {"mysql", "postgresql"}:
            raise ValueError("relational target dialect must be mysql or postgresql")
        self.dialect = dialect
        self.mysql = dialect == "mysql"
        self.options = options or {}
        self.naming: dict[str, str] = {}
        self.not_translated: list[dict[str, str]] = []
        self.warnings: list[dict[str, str]] = []
        self.tables: list[dict[str, Any]] = []
        self.root_by_collection: dict[str, dict[str, Any]] = {}
        self.decisions: dict[tuple[str, str], FieldDecision] = {}
        self.thresholds = Thresholds.from_mapping(self.options.get("thresholds"))
        self.registry = NameRegistry(max_length=int(self.options.get("naming", {}).get("max_identifier_length", 64 if self.mysql else 63)))
        self.width_by_table: dict[str, int] = {}
        self.column_registries: dict[str, NameRegistry] = {}

    def emit(self, document_ir: DocumentIR | dict[str, Any], decisions: list[FieldDecision] | list[dict[str, Any]], *, project_id: str = "") -> RelationalArtifacts:
        ir = document_ir if isinstance(document_ir, DocumentIR) else DocumentIR.model_validate(document_ir)
        parsed_decisions = [item if isinstance(item, FieldDecision) else FieldDecision.model_validate(item) for item in decisions]
        self.decisions = {(item.collection, item.path): item for item in parsed_decisions}
        self.not_translated = []
        self.warnings = []
        self.tables = []
        self.root_by_collection = {}
        self.width_by_table = {}
        self.naming = {}
        self.column_registries = {}
        self.registry = NameRegistry(max_length=int(self.options.get("naming", {}).get("max_identifier_length", 64 if self.mysql else 63)))
        collections = {collection.name: collection for collection in ir.collections}

        # Reserve stable root table names first, so generated child tables cannot collide with them.
        for collection in sorted(ir.collections, key=lambda item: item.name):
            table_name = self.registry.register(f"table:{collection.name}", collection.name)
            # MongoDB's _id is a source-side technical key. The relational target
            # owns its own surrogate key; source-to-target identity is kept in the
            # internal reverse-ID map table, not exposed as a business column.
            root = self._new_table(table_name, collection.name, "root", source_path="", parent_table=None)
            if self.mysql:
                root["columns"].append(self._column("id", "BIGINT UNSIGNED NOT NULL AUTO_INCREMENT", False, source_path="$surrogate", auto_increment=True))
            else:
                root["columns"].append(self._column("id", "BIGINT GENERATED BY DEFAULT AS IDENTITY", False, source_path="$surrogate", auto_increment=True))
            root["primary_key"] = ["id"]
            root["legacy_id_column"] = None
            root["id_column"] = "id"
            # API row-level optimistic concurrency is independent of source identity.
            root["columns"].append(self._column("row_version", "BIGINT NOT NULL DEFAULT 1", False, source_path="$row_version"))
            on_orphan = str((self.options.get("etl") or {}).get("on_orphan", self.options.get("on_orphan", "DLQ"))).upper()
            if on_orphan == "STUB":
                root["columns"].append(self._column("is_stub", "TINYINT(1) NOT NULL DEFAULT 0" if self.mysql else "BOOLEAN NOT NULL DEFAULT FALSE", False, source_path="$is_stub"))
            self.root_by_collection[collection.name] = root
            self.tables.append(root)
            self.width_by_table[table_name] = 128

        # Compile fields after all root PKs are known, so references can target later collections.
        for collection in sorted(ir.collections, key=lambda item: item.name):
            root = self.root_by_collection[collection.name]
            for node in sorted(collection.fields, key=lambda item: item.path):
                if node.path == "_id":
                    continue
                self._process_node(node, collection.name, root, root["id_column"], prefix="", ancestor_required=True)
            self._add_document_indexes(collection, root)

        # Internal source-ID map keeps MongoDB IDs out of business tables while
        # preserving retry, deduplication, and reference resolution semantics.
        self.tables.append({
            "name": "_synapse_reverse_idmap", "collection": "_synapse", "role": "system", "source_path": "",
            "parent_table": None, "columns": [
                self._column("source_namespace", "VARCHAR(128) NOT NULL", False),
                self._column("source_collection", "VARCHAR(255) NOT NULL", False),
                self._column("source_key_hash", "CHAR(64) NOT NULL", False),
                self._column("target_table", "VARCHAR(255) NOT NULL", False),
                self._column("target_id", "BIGINT UNSIGNED NOT NULL" if self.mysql else "BIGINT NOT NULL", False),
            ], "primary_key": ["source_namespace", "source_collection", "source_key_hash"],
            "id_column": "", "legacy_id_column": None,
            "unique_constraints": [], "foreign_keys": [], "indexes": [], "checks": [],
        })

        # Reverse-only checkpoint table: the authoritative reverse checkpoint commits with data.
        self.tables.append({
            "name": "_synapse_checkpoint", "collection": "_synapse", "role": "system", "source_path": "",
            "parent_table": None, "columns": [
                self._column("job_id", "VARCHAR(128) NOT NULL", False), self._column("unit_id", "VARCHAR(255) NOT NULL", False),
                self._column("stage", "VARCHAR(32) NOT NULL", False), self._column("last_key", "JSON" if self.mysql else "JSONB", True),
                self._column("batch_seq", "BIGINT NOT NULL DEFAULT 0", False), self._column("rows_done", "BIGINT NOT NULL DEFAULT 0", False),
                self._column("docs_written", "BIGINT NULL", True), self._column("errors", "BIGINT NOT NULL DEFAULT 0", False),
                self._column("plan_hash", "VARCHAR(80) NOT NULL", False), self._column("fence", "BIGINT NOT NULL", False),
                self._column("status", "VARCHAR(32) NOT NULL", False), self._column("updated_at", "TIMESTAMP NOT NULL" if self.mysql else "TIMESTAMPTZ NOT NULL", False),
            ], "primary_key": ["job_id", "unit_id", "stage"], "id_column": "", "legacy_id_column": None,
            "unique_constraints": [], "foreign_keys": [], "indexes": [], "checks": [],
        })
        pre = self._render_preload()
        post = self._render_postload()
        verify = self._render_verify()
        return RelationalArtifacts(pre, post, verify, self.tables, dict(sorted(self.naming.items())), self.not_translated, self.warnings)

    def _new_table(self, name: str, collection: str, role: str, *, source_path: str, parent_table: str | None) -> dict[str, Any]:
        return {"name": name, "collection": collection, "role": role, "source_path": source_path,
                "parent_table": parent_table, "columns": [], "primary_key": [], "id_column": "",
                "legacy_id_column": None, "unique_constraints": [], "foreign_keys": [], "indexes": [], "checks": []}

    def _column(self, name: str, sql_type: str, nullable: bool, *, source_path: str = "", auto_increment: bool = False) -> dict[str, Any]:
        return {"name": name, "sql_type": sql_type, "nullable": nullable, "source_path": source_path, "auto_increment": auto_increment}

    def _constraint_name(self, prefix: str, table: str, columns: list[str]) -> str:
        base = f"{prefix}_{table}_{'_'.join(columns)}"
        return self.registry.register(f"constraint:{base}", base)

    def _action(self, collection: str, node: FieldNode) -> ReverseAction:
        decision = self.decisions.get((collection, node.path))
        return decision.effective_action if decision else ReverseAction.PLAIN_COLUMN

    def _column_name(self, collection: str, table: dict[str, Any], path: str, prefix: str = "") -> str:
        key = f"column:{collection}:{table['name']}:{path}"
        candidate = flatten_path(path, max_length=self.registry.max_length)
        column_registry = self.column_registries.get(table["name"])
        if column_registry is None:
            column_registry = NameRegistry(max_length=self.registry.max_length)
            column_registry.seed(column["name"] for column in table["columns"])
            self.column_registries[table["name"]] = column_registry
        name = column_registry.register(key, candidate)
        self.naming[f"{collection}.{path}"] = name
        return name

    def _nullable(self, node: FieldNode, ancestor_required: bool) -> bool:
        if node.declared and node.declared.required and ancestor_required:
            return False
        if node.empty_rate == 0 and node.sample_size:
            from synapse.domain.heuristics.reverse import wilson_interval
            lower = wilson_interval(round(node.presence_rate * node.sample_size), node.sample_size)[0]
            if lower >= 0.995 and ancestor_required:
                return False
        return True

    def _type_for(self, node: FieldNode, action: ReverseAction) -> SqlTypeSpec:
        if action == ReverseAction.DEMOTE_TO_VARCHAR:
            length = max(node.string_stats.max_len if node.string_stats else 0, node.string_stats.p99_len * 2 if node.string_stats else 0)
            bucket = next((size for size in (32, 64, 128, 255, 512, 1024, 4096, 16383) if size >= max(length, 32)), None)
            return SqlTypeSpec(f"VARCHAR({bucket})" if bucket else ("TEXT" if self.mysql else "TEXT"))
        return bson_to_sql(node, dialect=self.dialect, nullable=self._nullable(node, True))

    def _add_column(self, table: dict[str, Any], collection: str, node: FieldNode, path: str, *, prefix: str = "", ancestor_required: bool = True) -> str:
        name = self._column_name(collection, table, path, prefix)
        action = self._action(collection, node)
        type_spec = self._type_for(node, action)
        nullable = self._nullable(node, ancestor_required)
        if action == ReverseAction.RETAIN_AS_JSON:
            type_spec = SqlTypeSpec("JSON" if self.mysql else "JSONB")
            nullable = True
        if action == ReverseAction.DEMOTE_TO_VARCHAR:
            nullable = self._nullable(node, ancestor_required)
        if not any(column["name"] == name for column in table["columns"]):
            table["columns"].append(self._column(name, type_spec.sql_type, nullable, source_path=path))
            self.width_by_table[table["name"]] = self.width_by_table.get(table["name"], 0) + self._estimated_column_width(node, type_spec.sql_type)
            self._add_declared_checks(table, name, node)
        return name

    def _estimated_column_width(self, node: FieldNode, sql_type: str) -> int:
        match = re.match(r"(?:VAR)?CHAR\((\d+)\)", sql_type.upper())
        if match:
            return min(4 * int(match.group(1)) + 2, 65_537) if self.mysql else int(match.group(1)) + 4
        if "TEXT" in sql_type.upper() or "JSON" in sql_type.upper():
            return 768
        if "DECIMAL" in sql_type.upper() or "NUMERIC" in sql_type.upper(): return 16
        if any(kind in sql_type.upper() for kind in ("BIGINT", "DOUBLE", "TIMESTAMP")): return 8
        return 4

    @staticmethod
    def _sql_check_type(sql_type: str) -> str:
        normalized = sql_type.upper()
        if "BOOLEAN" in normalized or re.search(r"\bTINYINT\s*\(\s*1\s*\)", normalized):
            return "boolean"
        if re.search(r"\b(?:SMALLINT|INTEGER|INT|BIGINT|TINYINT|DECIMAL|NUMERIC|REAL|FLOAT|DOUBLE)\b", normalized):
            return "numeric"
        if re.search(r"\b(?:CHAR|VARCHAR|TEXT|CITEXT)\b", normalized):
            return "text"
        return "other"

    def _add_declared_checks(self, table: dict[str, Any], column_name: str, node: FieldNode) -> None:
        declared = node.declared
        if declared is None:
            return
        qcol = quote_identifier(column_name, self.dialect)
        column_type = next((item.get("sql_type", "") for item in table["columns"] if item.get("name") == column_name), "")
        category = self._sql_check_type(column_type)
        source = f"{table['collection']}.{node.path}"

        if declared.enum:
            enum_values = list(declared.enum)
            non_null_values = [value for value in enum_values if value is not None]
            compatible = (
                (category == "boolean" and all(isinstance(value, bool) for value in non_null_values))
                or (category == "numeric" and all(isinstance(value, (int, float)) and not isinstance(value, bool) for value in non_null_values))
                or (category == "text" and all(isinstance(value, str) for value in non_null_values))
            )
            if compatible:
                predicates: list[str] = []
                if non_null_values:
                    values = ", ".join(self._literal(value, sql_type=column_type) for value in non_null_values)
                    predicates.append(f"{qcol} IN ({values})")
                if len(non_null_values) != len(enum_values):
                    predicates.append(f"{qcol} IS NULL")
                if predicates:
                    sql = " OR ".join(predicates)
                    table["checks"].append({"name": self._constraint_name("chk", table["name"], [column_name, "enum"]),
                                            "sql": f"({sql})"})
            else:
                self.not_translated.append({"source": source,
                                            "reason": f"enum validator was omitted because its values are incompatible with target SQL type {column_type!r}."})

        numeric_bound = declared.minimum is not None or declared.maximum is not None
        if numeric_bound and category != "numeric":
            self.not_translated.append({"source": source,
                                        "reason": f"numeric validator bounds were omitted because target column {column_name!r} uses non-numeric SQL type {column_type!r}."})
        elif declared.minimum is not None and declared.maximum is not None:
            sql = f"{qcol} BETWEEN {declared.minimum} AND {declared.maximum}"
            table["checks"].append({"name": self._constraint_name("chk", table["name"], [column_name, "range"]), "sql": sql})
        elif declared.minimum is not None:
            table["checks"].append({"name": self._constraint_name("chk", table["name"], [column_name, "min"]), "sql": f"{qcol} >= {declared.minimum}"})
        elif declared.maximum is not None:
            table["checks"].append({"name": self._constraint_name("chk", table["name"], [column_name, "max"]), "sql": f"{qcol} <= {declared.maximum}"})

        if declared.pattern:
            if category != "text":
                self.not_translated.append({"source": source,
                                            "reason": f"pattern validator was omitted because target column {column_name!r} uses non-text SQL type {column_type!r}."})
            else:
                pattern = self._literal(declared.pattern, sql_type=column_type)
                expression = f"REGEXP_LIKE({qcol}, {pattern})" if self.mysql else f"{qcol} ~ {pattern}"
                table["checks"].append({"name": self._constraint_name("chk", table["name"], [column_name, "pattern"]), "sql": expression})

    def _literal(self, value: Any, *, sql_type: str = "") -> str:
        if value is None: return "NULL"
        if value is True: return "1" if self.mysql else "TRUE"
        if value is False: return "0" if self.mysql else "FALSE"
        if isinstance(value, (int, float)): return str(value)
        return "'" + str(value).replace("'", "''") + "'"

    def _process_node(self, node: FieldNode, collection: str, owner: dict[str, Any], owner_id_column: str, *, prefix: str, ancestor_required: bool) -> None:
        action = self._action(collection, node)
        if node.kind == FieldKind.OBJECT:
            if action == ReverseAction.FLATTEN_COLUMNS:
                estimated = sum(self._estimate_node_width(child) for child in node.children)
                current = self.width_by_table.get(owner["name"], 0)
                if self.mysql and current + estimated > self.thresholds.flatten_row_limit_bytes:
                    action = ReverseAction.SIDE_TABLE_OPTIONAL
                    self.warnings.append({"code": "RH5_WIDTH_FALLBACK", "message": f"{collection}.{node.path} flattened width would exceed the MySQL {self.thresholds.flatten_row_limit_bytes}-byte in-page row budget; emitted as an optional side table."})
            if action == ReverseAction.FLATTEN_COLUMNS:
                required = ancestor_required and bool(node.declared and node.declared.required)
                for child in sorted(node.children, key=lambda item: item.path):
                    self._process_node(child, collection, owner, owner_id_column, prefix=prefix, ancestor_required=required)
                return
            if action == ReverseAction.SIDE_TABLE_OPTIONAL:
                side_name = child_table_name(owner["name"], node.name, singularize=bool(self.options.get("naming", {}).get("singularize_tables", False)), max_length=self.registry.max_length)
                side_name = self.registry.register(f"table:{collection}:{node.path}:side", side_name)
                side = self._new_table(side_name, collection, "side", source_path=node.path, parent_table=owner["name"])
                parent_col = self._column_name(collection, side, owner["name"] + "_id", prefix="")
                parent_type = self._column_type(owner, owner_id_column)
                side["columns"].append(self._column(parent_col, parent_type, False, source_path=node.path))
                side["primary_key"] = [parent_col]
                side["id_column"] = parent_col
                side["foreign_keys"].append(self._fk([parent_col], owner["name"], [owner_id_column], "CASCADE", side_name))
                self.tables.append(side)
                self.width_by_table[side_name] = 32
                required = ancestor_required and bool(node.declared and node.declared.required)
                for child in sorted(node.children, key=lambda item: item.path):
                    self._process_node(child, collection, side, parent_col, prefix=node.path, ancestor_required=required)
                return
            self._add_column(owner, collection, node, node.path, prefix=prefix, ancestor_required=ancestor_required)
            return

        if node.kind == FieldKind.ARRAY:
            if action == ReverseAction.EXTRACT_JUNCTION:
                self._make_junction(node, collection, owner, owner_id_column)
                return
            if action == ReverseAction.UNNEST_TO_TABLE:
                self._make_array_table(node, collection, owner, owner_id_column)
                return
            self._add_column(owner, collection, node, node.path, prefix=prefix, ancestor_required=ancestor_required)
            return

        if action == ReverseAction.FK_COLUMN and node.ref_target:
            name = self._column_name(collection, owner, node.path, prefix)
            target = self.root_by_collection.get(node.ref_target.collection)
            if target is None:
                type_spec = bson_to_sql(node, dialect=self.dialect, context="unresolved_reference")
                self.not_translated.append({"source": f"{collection}.{node.path}", "reason": f"Reference target {node.ref_target.collection!r} is not in this plan; stored as a legacy identifier."})
                target_type = type_spec.sql_type
            else:
                target_type = "BIGINT UNSIGNED" if self.mysql and target["id_column"] == "id" else ("BIGINT" if target["id_column"] == "id" else self._column_type(target, target["id_column"]))
            if not any(column["name"] == name for column in owner["columns"]):
                # Root references are populated in phase 2 after every root has
                # an internal target-ID mapping; keep the column nullable during
                # phase 1 so cyclic/out-of-order references can be resolved later.
                owner["columns"].append(self._column(name, target_type, True, source_path=node.path))
                self.width_by_table[owner["name"]] = self.width_by_table.get(owner["name"], 0) + 8
            if target is not None:
                owner["foreign_keys"].append(self._fk([name], target["name"], [target["id_column"]], "RESTRICT", owner["name"]))
            return

        self._add_column(owner, collection, node, node.path, prefix=prefix, ancestor_required=ancestor_required)

    def _column_type(self, table: dict[str, Any], column_name: str) -> str:
        raw = next(column["sql_type"] for column in table["columns"] if column["name"] == column_name)
        raw = re.sub(r"\s+NOT NULL\b", "", raw, flags=re.I)
        raw = re.sub(r"\s+AUTO_INCREMENT\b", "", raw, flags=re.I)
        # A generated PK's identity clause is not part of its underlying SQL type.
        # Strip it before DEFAULT handling so `BY DEFAULT AS IDENTITY` is not cut
        # into the invalid fragment `BY IDENTITY` in child FK columns.
        raw = re.sub(r"\s+GENERATED\s+(?:ALWAYS|BY\s+DEFAULT)\s+AS\s+IDENTITY\b(?:\s*\([^)]*\))?", "", raw, flags=re.I)
        raw = re.sub(r"\s+DEFAULT\s+[^ ]+", "", raw, flags=re.I)
        return raw.strip()

    def _estimate_node_width(self, node: FieldNode) -> int:
        if node.kind == FieldKind.OBJECT:
            return sum(self._estimate_node_width(child) for child in node.children)
        if node.kind == FieldKind.ARRAY:
            return 0
        if node.string_stats:
            return min(max(node.string_stats.max_len, node.string_stats.p99_len * 2, 32) * (4 if self.mysql else 1) + 2, 65_537)
        return 16 if any(item.bson_type in {"decimal", "double", "long"} for item in node.types) else 8

    def _fk(self, columns: list[str], target_table: str, target_columns: list[str], on_delete: str, prefix: str) -> dict[str, Any]:
        name = self._constraint_name("fk", prefix, columns + [target_table])
        return {"name": name, "columns": columns, "target_table": target_table, "target_columns": target_columns, "on_delete": on_delete}

    def _make_array_table(self, node: FieldNode, collection: str, owner: dict[str, Any], owner_id_column: str) -> None:
        table_name = child_table_name(owner["name"], node.name, singularize=bool(self.options.get("naming", {}).get("singularize_tables", False)), max_length=self.registry.max_length)
        table_name = self.registry.register(f"table:{collection}:{node.path}:array", table_name)
        child = self._new_table(table_name, collection, "child", source_path=node.path, parent_table=owner["name"])
        child["columns"].append(self._column("id", "BIGINT UNSIGNED NOT NULL AUTO_INCREMENT" if self.mysql else "BIGINT GENERATED BY DEFAULT AS IDENTITY", False, source_path="$surrogate", auto_increment=True))
        child["primary_key"] = ["id"]
        child["id_column"] = "id"
        parent_name = self._column_name(collection, child, owner["name"] + "_id")
        owner_key_type = self._column_type(owner, owner_id_column)
        child["columns"].append(self._column(parent_name, owner_key_type, False, source_path=node.path))
        child["columns"].append(self._column("position", "INT NOT NULL", False, source_path=node.path + "[]:position"))
        child["unique_constraints"].append({"name": self._constraint_name("uq", table_name, [parent_name, "position"]), "columns": [parent_name, "position"]})
        child["foreign_keys"].append(self._fk([parent_name], owner["name"], [owner_id_column], "CASCADE", table_name))
        child["indexes"].append({"name": self._constraint_name("ix", table_name, [parent_name]), "columns": [parent_name], "unique": False})
        child["id_column_parent"] = parent_name
        self.tables.append(child)
        self.width_by_table[table_name] = 32
        if node.array and node.array.element_kind == FieldKind.OBJECT:
            for field in sorted(node.children, key=lambda item: item.path):
                self._process_node(field, collection, child, "id", prefix=node.path + "[]", ancestor_required=True)
        else:
            element_types = {item.bson_type for item in (node.array.element_types if node.array else []) if item.bson_type != "null"}
            value_type = bson_to_sql(element_types or {"string"}, dialect=self.dialect).sql_type
            child["columns"].append(self._column("value", value_type, True, source_path=node.path + "[]"))
            child["value_column"] = "value"

    def _make_junction(self, node: FieldNode, collection: str, owner: dict[str, Any], owner_id_column: str) -> None:
        ref = node.array.element_ref_target if node.array else None
        if ref is None:
            self._make_array_table(node, collection, owner, owner_id_column)
            self.warnings.append({"code": "UNRESOLVED_REFERENCE", "message": f"{collection}.{node.path} has no confirmed target; emitted a value table."})
            return
        target = self.root_by_collection.get(ref.collection)
        if target is None:
            self._make_array_table(node, collection, owner, owner_id_column)
            self.not_translated.append({"source": f"{collection}.{node.path}", "reason": f"Reference target {ref.collection!r} was not selected for this plan; emitted as a value table."})
            return
        table_name = child_table_name(owner["name"], ref.collection, singularize=False, max_length=self.registry.max_length)
        table_name = self.registry.register(f"table:{collection}:{node.path}:junction", table_name)
        junction = self._new_table(table_name, collection, "junction", source_path=node.path, parent_table=owner["name"])
        parent_col = self._column_name(collection, junction, owner["name"] + "_id")
        target_col = self._column_name(collection, junction, ref.collection.rstrip("s") + "_id")
        parent_type = self._column_type(owner, owner_id_column)
        target_type = self._column_type(target, target["id_column"])
        junction["columns"].extend([self._column(parent_col, parent_type, False, source_path=node.path), self._column(target_col, target_type, False, source_path=node.path)])
        if self.options.get("reverse", {}).get("preserve_array_order", False):
            junction["columns"].append(self._column("position", "INT NOT NULL", False, source_path=node.path + "[]:position"))
            junction["primary_key"] = [parent_col, "position"]
            junction["unique_constraints"].append({"name": self._constraint_name("uq", table_name, [parent_col, target_col]), "columns": [parent_col, target_col]})
        else:
            junction["primary_key"] = [parent_col, target_col]
        junction["id_column"] = parent_col
        junction["foreign_keys"].extend([
            self._fk([parent_col], owner["name"], [owner_id_column], "CASCADE", table_name),
            self._fk([target_col], target["name"], [target["id_column"]], "RESTRICT", table_name),
        ])
        junction["indexes"].append({"name": self._constraint_name("ix", table_name, [target_col]), "columns": [target_col], "unique": False})
        self.tables.append(junction)

    def _add_document_indexes(self, collection: Collection, root: dict[str, Any]) -> None:
        for index in collection.indexes:
            # MongoDB's technical `_id` and Synapse's generated `_legacy` lineage
            # metadata are not relational business columns. Their Mongo-only indexes
            # have no direct target column and must not become invalid SQL indexes.
            if any(path == "_id" or path == "_legacy" or path.startswith("_legacy.")
                   for path, _direction in index.keys):
                continue
            kind = index.index_type.lower()
            if kind in {"ttl", "text", "2dsphere", "hashed", "wildcard"} or index.expire_after_seconds is not None:
                alternatives = {"ttl": "scheduled purge", "text": "FULLTEXT", "2dsphere": "SPATIAL/generated GeoJSON", "hashed": "application hash column", "wildcard": "JSON generated columns"}
                self.not_translated.append({"source": f"{collection.name}.{index.name} ({kind})", "reason": f"no direct SQL equivalent; consider {alternatives.get(kind, 'manual review')}"})
                continue
            if index.partial_filter:
                self.not_translated.append({"source": f"{collection.name}.{index.name} (partial)",
                                            "reason": "partial-filter semantics are not safely expressible by this reverse plan; index omitted."})
                continue
            if index.sparse and index.unique:
                self.not_translated.append({"source": f"{collection.name}.{index.name} (sparse unique)",
                                            "reason": "sparse unique semantics differ from relational NULL uniqueness; index omitted."})
                continue
            mapped_columns: list[str] = []
            root_columns = {column["name"] for column in root["columns"]}
            unsupported_path: str | None = None
            for path, _direction in index.keys:
                mapped = self.naming.get(f"{collection.name}.{path}")
                if mapped is None:
                    mapped = self.naming.get(f"{collection.name}.{path.replace('.', '[] .').replace(' ', '')}")
                if mapped is None:
                    mapped = path.replace(".", "_").replace("[]", "")
                if mapped not in root_columns:
                    unsupported_path = path
                    break
                mapped_columns.append(mapped)
            if unsupported_path is not None:
                self.not_translated.append({"source": f"{collection.name}.{index.name}",
                                            "reason": f"index field {unsupported_path!r} is not a column in relational root table {root['name']!r}; index omitted."})
                continue
            root["indexes"].append({"name": self._constraint_name("ix", root["name"], mapped_columns),
                                    "columns": mapped_columns, "unique": index.unique,
                                    "directions": [int(direction) if isinstance(direction, int) else 1 for _, direction in index.keys],
                                    "partial_filter": None})

    def _render_preload(self) -> str:
        fragments: list[str] = []
        if self.mysql:
            fragments.append("SET SESSION sql_mode = 'STRICT_ALL_TABLES,NO_ZERO_DATE,NO_ZERO_IN_DATE,ERROR_FOR_DIVISION_BY_ZERO';")
        template = _ENV.get_template("create_table.sql.j2")
        for table in self.tables:
            columns = []
            for column in table["columns"]:
                qcol = quote_identifier(column["name"], self.dialect)
                raw_type = column["sql_type"]
                if column.get("auto_increment") and self.mysql and "AUTO_INCREMENT" not in raw_type.upper():
                    raw_type += " AUTO_INCREMENT"
                definition = f"{qcol} {raw_type} {'NULL' if column['nullable'] else 'NOT NULL'}"
                if "NOT NULL" in raw_type.upper() or "NULL" in raw_type.upper():
                    definition = f"{qcol} {raw_type}"
                columns.append(definition)
            for unique in table["unique_constraints"]:
                qcols = ", ".join(quote_identifier(col, self.dialect) for col in unique["columns"])
                if self.mysql:
                    columns.append(f"UNIQUE KEY {quote_identifier(unique['name'], self.dialect)} ({qcols})")
                else:
                    columns.append(f"CONSTRAINT {quote_identifier(unique['name'], self.dialect)} UNIQUE ({qcols})")
            primary = ", ".join(quote_identifier(col, self.dialect) for col in table["primary_key"])
            rendered = template.render(table_q=quote_identifier(table["name"], self.dialect), columns=columns,
                                       primary_key=primary, mysql=self.mysql,
                                       engine=self.options.get("mysql", {}).get("engine", "InnoDB"),
                                       charset=self.options.get("mysql", {}).get("charset", "utf8mb4"),
                                       collation=self.options.get("mysql", {}).get("collation", "utf8mb4_0900_ai_ci"))
            fragments.append(rendered.strip())
        return "\n\n".join(fragments) + "\n"

    def _render_postload(self) -> str:
        fragments: list[str] = []
        for table in self.tables:
            qtable = quote_identifier(table["name"], self.dialect)
            for fk in table["foreign_keys"]:
                local = ", ".join(quote_identifier(col, self.dialect) for col in fk["columns"])
                remote = ", ".join(quote_identifier(col, self.dialect) for col in fk["target_columns"])
                qtarget = quote_identifier(fk["target_table"], self.dialect)
                fragments.append(f"ALTER TABLE {qtable} ADD CONSTRAINT {quote_identifier(fk['name'], self.dialect)} FOREIGN KEY ({local}) REFERENCES {qtarget} ({remote}) ON DELETE {fk['on_delete']};")
            for index in table["indexes"]:
                unique = "UNIQUE " if index.get("unique") else ""
                columns = []
                directions = index.get("directions", [])
                for index_pos, col in enumerate(index["columns"]):
                    direction = directions[index_pos] if index_pos < len(directions) else 1
                    columns.append(f"{quote_identifier(col, self.dialect)} {'DESC' if direction == -1 else 'ASC'}")
                statement = f"CREATE {unique}INDEX {quote_identifier(index['name'], self.dialect)} ON {qtable} ({', '.join(columns)})"
                if index.get("partial_filter") and not self.mysql:
                    statement += " WHERE " + " AND ".join(f"{quote_identifier(key, self.dialect)} IS NOT NULL" for key in index["partial_filter"])
                fragments.append(statement + ";")
            for check in table["checks"]:
                fragments.append(f"ALTER TABLE {qtable} ADD CONSTRAINT {quote_identifier(check['name'], self.dialect)} CHECK ({check['sql']});")
        return "\n".join(fragments) + ("\n" if fragments else "")

    def _render_verify(self) -> str:
        fragments = ["-- Counts and post-load referential audits generated from the frozen table plan."]
        for table in self.tables:
            if table["role"] == "system":
                continue
            fragments.append(f"SELECT '{table['name']}' AS table_name, COUNT(*) AS row_count FROM {quote_identifier(table['name'], self.dialect)};")
            for fk in table["foreign_keys"]:
                local = " AND ".join(f"c.{quote_identifier(col, self.dialect)} = p.{quote_identifier(ref, self.dialect)}" for col, ref in zip(fk["columns"], fk["target_columns"], strict=True))
                fragments.append(f"SELECT COUNT(*) AS orphans FROM {quote_identifier(table['name'], self.dialect)} c LEFT JOIN {quote_identifier(fk['target_table'], self.dialect)} p ON {local} WHERE p.{quote_identifier(fk['target_columns'][0], self.dialect)} IS NULL;")
        return "\n".join(fragments) + "\n"


def emit_relational(document_ir: DocumentIR | dict[str, Any], decisions: list[FieldDecision] | list[dict[str, Any]], *, dialect: str = "mysql", options: dict[str, Any] | None = None, project_id: str = "") -> RelationalArtifacts:
    return RelationalEmitter(dialect=dialect, options=options).emit(document_ir, decisions, project_id=project_id)
